from __future__ import annotations

import json
import os
import re
import sys
from pathlib import Path

import psycopg2

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO))

import os as _os
CACHE = REPO / "data" / "exp" / _os.environ.get("EXP7M1_CACHE", "7m1_partner_count_2026.jsonl")
YEAR_FROM = _os.environ.get("EXP7M1_FROM", "2026-01-01")
YEAR_TO = _os.environ.get("EXP7M1_TO", "2026-12-31")
COMBO_RE = re.compile(r"^\s*(\d+)\s*=\s*(\d+)\s*-\s*([\d,]+)")


def build_cache() -> None:
    from src.odds_prediction import load_race_inputs, predict_board, _pl_trio

    conn = psycopg2.connect(os.environ["KEIRIN_DB_URL"])
    cur = conn.cursor()
    cur.execute(
        "SELECT split_part(race_key,'#',1), race_date::text, pred_combo, trio_payout "
        "FROM keirin.picks_history WHERE rank='RANK_7M1' AND bet_amount>0 "
        "  AND pred_combo IS NOT NULL AND race_date >= %s AND race_date <= %s "
        "ORDER BY race_date, race_key", (YEAR_FROM, YEAR_TO))
    picks = []
    for rk, rd, pc, tp in cur.fetchall():
        m = COMBO_RE.match(pc or "")
        if m:
            picks.append((rk, rd, int(m.group(1)), int(m.group(2)),
                          [int(x) for x in m.group(3).split(",")], tp or 0))
    keys = [p[0] for p in picks]
    cur.execute(
        "SELECT race_key, frame_no, prediction_mark, pred_top3_pct, finish_order "
        "FROM keirin.wt_entries WHERE race_key = ANY(%s)", (keys,))
    ent: dict[str, list] = {}
    for r in cur.fetchall():
        ent.setdefault(r[0], []).append(r)
    conn.close()

    CACHE.parent.mkdir(parents=True, exist_ok=True)
    n_ok = n_skip = 0
    with CACHE.open("w") as fh:
        for rk, rd, a1, a2, rec_legs, trio in picks:
            es = ent.get(rk) or []
            top3 = sorted(int(e[1]) for e in es if e[4] in (1, 2, 3))
            mark = {int(e[1]): int(e[2] or 0) for e in es}
            p3 = {int(e[1]): float(e[3] or 0.0) for e in es}
            others = sorted(f for f in p3 if f not in (a1, a2))
            if len(top3) != 3 or len(others) != 5 or trio <= 0:
                n_skip += 1
                continue
            try:
                cars, mp3, pw, meta = load_race_inputs(rk)
                board = predict_board(cars, mp3, pw, meta)
                pl = _pl_trio(pw, cars)
            except Exception:
                n_skip += 1
                continue
            odds, prob = {}, {}
            bad = False
            for t in others:
                k = frozenset({a1, a2, t})
                o, p = board.get(k), pl.get(k)
                if not o or o <= 0 or p is None:
                    bad = True
                    break
                odds[t], prob[t] = float(o), float(p)
            if bad:
                n_skip += 1
                continue
            fh.write(json.dumps({
                "rk": rk, "date": rd, "a1": a1, "a2": a2, "others": others,
                "rec_legs": rec_legs, "top3": top3, "trio": trio,
                "mark": mark, "p3": p3, "odds": odds, "prob": prob}) + "\n")
            n_ok += 1
            if n_ok % 200 == 0:
                print(f"  {n_ok} 件", flush=True)
    print(f"cache: {n_ok} 件 / skip {n_skip} -> {CACHE}")


if __name__ == "__main__":
    build_cache()
