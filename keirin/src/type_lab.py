def _tau_adaptive_legs(shape: "RaceShape", plan: Plan,
                       pred_odds: Mapping, probs: Mapping,
                       min_mean_payout: float = MIN_MEAN_PAYOUT):
    """**平均想定払戻がゲートを割らない最大点数**まで積んだ買い目と賭け金。

    `plan.max_legs` を `TAU_ADAPTIVE_MIN_LEGS`〜`TAU_ADAPTIVE_MAX_LEGS` で振り、
    ゲートを通る中で**最も点数の多いもの**を採る。組めなければ `None`。

    🔴 **`mean_expected_payout` を直接見ること。** `Σ(1/予測オッズ)` で代用できるのは
       ダッチ配分のときだけで、`conf` 傾斜では等式が成り立たない。
    🔴 **点数を増やす側も試す。** 減らすだけだと効果が半分以下になる
       （+0.91 [−0.10,+1.99]＝確認窓で CI が 0 を跨ぐ）。
    """
    best = None
    for k in range(TAU_ADAPTIVE_MIN_LEGS, TAU_ADAPTIVE_MAX_LEGS + 1):
        got = _build_plan(shape, replace(plan, max_legs=k, tau_adaptive=False),
                          pred_odds, probs)
        if not got:
            continue
        if mean_expected_payout(got[1], pred_odds) <= min_mean_payout:
            break          # 点数を増やすほど平均は下がる一方なので、ここで打ち切る
        best = got
    return best


def _build_plan(shape: "RaceShape", plan: Plan,
                pred_odds: Mapping, probs: Mapping):
    """買い目と賭け金。賭け金 0 円の点（`allocate` が落とす）は返さない。"""
    legs = build_legs(shape, plan, pred_odds, probs)
    if not legs:
        return None
    stakes = allocate(legs, pred_odds, probs, plan)
    if not stakes:
        # 🔴 最低2倍の床が置けないだけなら、変更前の配分で売る（見送りにしない）。
        fb = alloc_fallback(plan)
        if fb is not None:
            stakes = allocate(legs, pred_odds, probs, fb)
    if not stakes:
        return None
    return [c for c in legs if c in stakes], stakes


def build_with_gate_fallback(shape: "RaceShape", plan: Plan,
                             pred_odds: Mapping, probs: Mapping,
                             n_entries: int = 7,
                             min_mean_payout: float = MIN_MEAN_PAYOUT,
                             order_probs: Mapping | None = None):
    """買い目と賭け金を作る。**入稿ゲートに落ちるなら代替の買い方へ切り替える。**

    戻り値は `(legs, stakes, plan_used)`。組めなければ `None`。

    🔴 **paper も live もこの関数を通すこと。** 生成側だけに書くと、検証台と
       本番で母集団が割れる（型ラボが「正本は1つ」を掲げている理由そのもの）。

    🔴 **7車だけに掛ける。** 測ったのは7車で、9車は同じ買い方でも予測オッズの
       分布が丸ごと違う（目が多いぶん高く出る）ため、同じ 15倍 は別の操作になる。
       このリポジトリは車数をまたいだ移植で繰り返し失敗している（7C の定数・
       3ヘッド軸・7M1）。9車で使うなら9車の窓で測り直してから。
    """
    def _done(got, pl: Plan):
        # 🔴 **ライン決着への差し替えは最後に掛ける**（買い方が確定してから）。
        #    ゲートを割るなら差し替えないので、ここで母集団は動かない。
        legs, stakes = apply_line_swap(shape, pl, got[0], got[1],
                                       pred_odds, probs, min_mean_payout)
        # 🔴 **並べ替えはさらにその後**（2026-09-11）。差し替えが「どの3車を買うか」を
        #    決めてから、「その3車をどの並びで買うか」を直す。順序が逆だと
        #    差し替え先の並びを評価できない。こちらもゲートを割るなら掛けない。
        #    ⚠️ `order_probs` が無ければ何もしない（後方互換・欠測は素通し）。
        legs, stakes = apply_order_swap(pl, legs, stakes, pred_odds,
                                        order_probs, min_mean_payout)
        # 🔴 **押さえ目は最後**（2026-09-11）。買い目と並びが確定してから
        #    「まだ買っていない人気薄の3着」を固定100円で足す。ここも
        #    ゲートを割るなら足さない＝在庫は1件も減らない。
        legs, stakes = apply_osae(shape, pl, legs, stakes, pred_odds, probs,
                                  min_mean_payout)
        return legs, stakes, pl

    if n_entries != 7:
        # 🔴 **帯下の差込は7車で測った操作**（`_insert_underband`）。9車は予測オッズの
        #    分布が丸ごと違ううえ `GATE_FALLBACK` も掛からない（ゲートに落ちたら
        #    そのまま在庫が消える）ので、ここで外す。9車で使うなら9車の窓で測り直すこと。
        pl = replace(plan, underband_min=0.0) if plan.underband_min else plan
        got = _build_plan(shape, pl, pred_odds, probs)
        return _done(got, pl) if got else None
    def _build(pl: Plan):
        # 🔴 τ適応は**7車だけ**（上の `n_entries != 7` で既に分岐済み）。
        #    ゲートを通る最大点数を探し、見つからなければ従来どおり組む。
        if pl.tau_adaptive:
            got = _tau_adaptive_legs(shape, pl, pred_odds, probs, min_mean_payout)
            if got:
                return got
        return _build_plan(shape, pl, pred_odds, probs)

    got = _build(plan)
    fbs = GATE_FALLBACK.get(plan.key) or ()
    if not fbs:
        return _done(got, plan) if got else None
    # 本命が組めた上でゲートを通るなら、そのまま使う（既存の行は書き換えない）
    if got and mean_expected_payout(got[1], pred_odds) > min_mean_payout:
        return _done(got, plan)
    # 🔴 **上から順に試す。** 途中で通ったらそこで止める（`F_hit` は
    #    「帯15倍＋差込」→「帯15倍」の2段。差込が割ったぶんを後段が拾うので
    #    在庫が減らない）。
    for fb in fbs:
        alt = _build(fb)
        if alt and mean_expected_payout(alt[1], pred_odds) > min_mean_payout:
            return _done(alt, fb)
    # どれもゲートに落ちるなら、元の結果をそのまま返す（見送りの判断は入稿側）
    return _done(got, plan) if got else None


#: 上帯の配分は必ずダッチ（∝1/予測オッズ）。どの点が当たっても払戻が揃うので、
#: 薄いスライスでも「当たれば投資を超える」が構造的に保たれる。
_UPPER_PLAN = Plan("_upper", "?", "trifecta", "prob_top", 0, alloc="dutch")


def _upper_legs(band: UpperBand, pred_odds: Mapping, probs: Mapping,
                base_legs: Sequence = ()):
    """上帯ひと切れの買い目。組めなければ None。

    `perm_fill` だけ**下帯の買い目**を見る（そこから3車の集合を数える）。
    """
    if band.structure == "perm_fill":
        bought = [tuple(c) for c in base_legs]
        cnt: dict = {}
        for c in bought:
            key = frozenset(c)
            cnt[key] = cnt.get(key, 0) + 1
        have = set(bought)
        cand = []
        for trio, n in cnt.items():
            if n < band.min_bought:
                continue
            for p in itertools.permutations(sorted(trio)):
                if p in have:
                    continue
                o = pred_odds.get(p)
                if _pos(o) and float(o) >= band.min_odds:
                    cand.append(p)
        cand.sort(key=lambda k: -float(probs.get(k, 0.0)))
        out = cand[:band.max_legs] if band.max_legs else cand
        return out or None
    cand = [tuple(k) for k, v in pred_odds.items()
            if _pos(v) and len(set(k)) == 3
            and float(v) >= band.min_odds
            and (not band.max_odds or float(v) <= band.max_odds)]
    cand.sort(key=lambda k: -float(probs.get(k, 0.0)))
    if band.structure == "prob_top":
        out = cand[:band.max_legs or 8]
    elif band.structure == "signboard":
        cap = float(band.budget) / float(band.target)
        out, s = [], 0.0
        for k in cand:
            o = float(pred_odds[k])
            if s + 1.0 / o > cap:
                continue
            out.append(k)
            s += 1.0 / o
    else:
        return None
    return out or None


def add_upper_band(legs: Sequence, stakes: Mapping, plan: Plan,
                   pred_odds: Mapping, probs: Mapping,
                   n_entries: int = 7,
                   bands: Sequence[UpperBand] | None = None,
                   ) -> tuple[list, dict, dict]:
    """下帯の賭け金を縮めて上帯を重ねる。戻り値 `(legs, stakes, roles)`。

    `roles` は 買い目 -> `UpperBand.kind`（下帯は `ROLE_BASE`）。

    🔴 **掛けられないときは今日と同じ商品をそのまま返す**（例外を投げない・
       黙って別物にしない）。掛けないのは次の場合:
       ①7車以外 ②三連複プラン ③上帯が1つでも組めない ④下帯を縮めると組めない。
    🔴 **重複した目は賭け金を足し、役割は下帯のまま**。同じ目を2行に分けると
       入稿でも採点でも二重に数えられる。
    🔴 **呼ぶのは `build_with_gate_fallback` の後**。ゲートの判定（と `F_hit` の
       帯15倍フォールバック）は**下帯を予算全額で組んだ状態**で行う——ここを
       混ぜると入稿母集団が静かに変わる（上の節）。

    >>> po = {(1, 2, 3): 5.0, (1, 3, 2): 9.0, (2, 1, 3): 40.0, (3, 2, 1): 90.0}
    >>> pr = {(1, 2, 3): .2, (1, 3, 2): .1, (2, 1, 3): .03, (3, 2, 1): .01}
    >>> plan = PLANS["F_hit"]                 # 掛かるのは E_hit / F_hit だけ
    >>> legs = [(1, 2, 3), (1, 3, 2)]         # 同じ3車の並びを2通り買っている
    >>> st = allocate(legs, po, pr, plan)
    >>> sum(st.values())
    10000

    ⚠️ 上帯どうしが同じ目を選ぶことは起こりうる（複数の切れを入れた場合）。
       そのときは賭け金が厚くなるだけで行は増えない。`perm_fill` は定義上
       下帯と重ならない（まだ買っていない並びしか拾わない）。

    🔴 いま `UPPER_BANDS` は**空**（2026-09-04 夕方に切り戻し）なので、既定では
       何も重ならない。仕組みを見るときは `bands=` を明示する。

    >>> add_upper_band(legs, st, plan, po, pr)[1] == st      # 既定は素通し
    True
    >>> lg2, st2, roles = add_upper_band(legs, st, plan, po, pr,
    ...                                  bands=(_PERM_BAND,))
    >>> sum(st2.values())
    10000
    >>> sum(v for k, v in st2.items() if roles[k] == ROLE_BASE)
    8000
    >>> sorted(set(roles.values()))
    ['base', 'perm']
    >>> sorted(k for k, v in roles.items() if v == "perm")
    [(2, 1, 3), (3, 2, 1)]
    """
    # 🔴 既定は**呼ばれた時点の** `UPPER_BANDS` を読む。引数の既定値にすると
    #    def 時に束縛され、定数を差し替えても効かない（検証で実際に踏んだ）。
    bands = UPPER_BANDS if bands is None else bands
    plain = (list(legs), dict(stakes), {tuple(c): ROLE_BASE for c in legs})
    if (not bands or int(n_entries or 0) != UPPER_BAND_N_ENTRIES
            or plan.bet_type != "trifecta"
            or (UPPER_BAND_PLANS and plan.key not in UPPER_BAND_PLANS)):
        return plain
    up_total = sum(b.budget for b in bands)
    base = allocate(legs, pred_odds, probs, plan, budget=BUDGET - up_total)
    if not base:
        return plain
    out_legs = [c for c in legs if c in base]
    out: dict = dict(base)
    roles = {c: ROLE_BASE for c in out_legs}
    for band in bands:
        ul = _upper_legs(band, pred_odds, probs, legs)
        if not ul:
            return plain
        us = allocate(ul, pred_odds, probs, _UPPER_PLAN, budget=band.budget)
        if not us:
            return plain
        for c in ul:
            if c not in us:
                continue
            if c in out:
                out[c] += us[c]
            else:
                out[c] = us[c]
                out_legs.append(c)
                roles[c] = band.kind
    return out_legs, out, roles


def split_legs_by_role(legs: Sequence[Mapping], role: str = ROLE_BASE) -> list:
    """行の `legs`（dict の列）から役割で絞る。**役割が無い行は下帯とみなす**。

    >>> split_legs_by_role([{"combo": "1-2-3"}, {"combo": "4-5-6", "role": "band"}])
    [{'combo': '1-2-3'}]
    """
    return [lg for lg in legs if (lg.get("role") or ROLE_BASE) == role]


def min_expected_payout(stakes: Mapping, pred_odds: Mapping) -> float:
    """買った点の**最低**想定払戻（円）。信頼度傾斜の床がここに出る。"""
    if not stakes:
        return 0.0
    return min(stakes[c] * float(pred_odds[c]) for c in stakes)


def rule_version(n_entries: int = 7) -> str:
    """`PLANS` と主要定数から導く版。値を変えると自動で別世代になる。

    🔴 **7車のハッシュは車数の規則を含めない。** 含めると 9車を足しただけで
       既存の 7車 53,017行と新しい行の版が割れ、「規則が変わった」と誤読される
       （7車の買い方は一切変えていない）。9車だけ `NINE_CAR_TYPE_F_*` を混ぜて
       別世代にする — `paper9` の行は**全8プランで作った**ので、決勝限定へ絞った
       今の規則とは実際に別物だから。
    """
    import hashlib
    import json
    payload: dict = (
        {k: [v.bet_type, v.structure, v.n_partners, v.min_odds, v.max_odds,
             v.max_legs, round(v.sigma_max, 6), v.alloc, v.floor_mult]
         for k, v in sorted(PLANS.items())}
        | {"_axis": AXIS_SUM_FIRM, "_behind": BEHIND_MID, "_budget": BUDGET}

        # 🔴 看板枠は**プランの属性だけでは表せない**（計画払戻 T が `build_legs` の
        #    中で使われる）。ここに入れておかないと T を動かしても版が割れず、
        #    新旧の行が同じ `rule_version` で混ざる。
        | {"_sign": [list(SIGNBOARD_TYPES), SIGNBOARD_TARGET,
                     SIGNBOARD_MAX_ODDS, SIGNBOARD_N_ENTRIES,
                     sorted(SIGNBOARD_RACE_TYPES)]}

        # 🔴 ライン決着への差し替えも `PLANS` の属性では表せない（`build_with_gate_fallback`
        #    の中で効く）。ここへ入れないと対象プランや差し替え点数を動かしても
        #    版が割れず、新旧の行が同じ `rule_version` で混ざる（`_sign` と同じ理由）。
        #    ⚠️ 7車にも9車にも掛けているので、`if n_entries == 7` の中には入れない。
        | {"_line": [sorted(LINE_SWAP_PLANS), list(LINE_SWAP_LEGS),
                     LINE_SWAP_MIN_KEEP, LINE_SWAP_MIN_ODDS]})
    if n_entries == 7:
        # 🔴 フォールバックは `PLANS` に無いので、ここへ入れないと帯を動かしても
        #    版が割れず新旧の行が混ざる（`_sign` と同じ理由）。
        #    ⚠️ **7車のときだけ入れる。** 9車には掛けていないので、9車の版まで
        #       割ると「規則が変わった」と誤読される（車数の規則を7車のハッシュへ
        #       入れない、という既存の判断と同じ理由）。
        # 🔴 上帯も `PLANS` の外なので、ここへ入れないと帯や予算を動かしても
        #    版が割れず新旧の行が混ざる（`_sign` / `_fallback` と同じ理由）。
        payload["_upper"] = [[[b.kind, b.budget, b.structure, b.min_odds,
                               b.max_odds, b.max_legs, b.target, b.min_bought]
                              for b in UPPER_BANDS],
                             sorted(UPPER_BAND_PLANS)]
        # 🔴 **並びごと・順序も含めて載せる**（2026-09-08）。試す順を入れ替えると
        #    商品が変わるので、順序が版に効かないと新旧の行が混ざる。
        #    `underband_min` も入れる（代替側の差込がここにしか無いため）。
        payload["_fallback"] = {
            k: [[v.bet_type, v.structure, v.n_partners, v.min_odds, v.max_odds,
                 v.max_legs, round(v.sigma_max, 6), v.alloc, v.floor_mult,
                 v.underband_min]
                for v in vs]
            for k, vs in sorted(GATE_FALLBACK.items())}
        # 🔴 帯下の差込も上の一覧に入っていない属性なので、ここへ入れないと
        #    下限を動かしても版が割れず新旧の行が混ざる（`_sign` と同じ理由）。
        #    ⚠️ **9車では外している**ので 7車の側にだけ入れる。
        payload["_underband"] = {k: v.underband_min
                                 for k, v in sorted(PLANS.items()) if v.underband_min}
    if n_entries == 9:
        # 🔴 ルーティング（決勝以外を `F_line` へ）と Σ の上限は `PLANS` の
        #    属性だけでは表せないので、ここへ入れないと新旧の行が同じ
        #    `rule_version` で混ざる（`_sign` / `_line` と同じ理由）。
        payload["_sell9"] = [list(NINE_CAR_TYPE_F_RACE_TYPES),
                             list(NINE_CAR_TYPE_F_PLANS),
                             TYPE_F_SELL_LINE, TYPE_F_LINE_N_ENTRIES,
                             round(TRIO_LINE_SIGMA_MAX, 6), TRIO_LINE_MIN_LEGS]
    return hashlib.sha1(
        json.dumps(payload, sort_keys=True, ensure_ascii=False).encode()
    ).hexdigest()[:12]
