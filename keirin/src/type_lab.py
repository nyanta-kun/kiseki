#:      1.00    8/ 9%  **-0.18/-0.19**  105/108%
#:
#: 🟢 **効いたのは「差し替え先そのものの安さ」に下限を置く形**（比率ではなく絶対値）。
#:    安すぎる候補を飛ばして次に安いものを採るので、**発動はむしろ増える**
#:    （安すぎてゲートに落ちていた分が通るようになる）:
#:
#:      下限     発動   Δ的中pt        既存的中の払戻維持   ROI(探索/確認)
#:      なし   40/44%  +2.53/+3.13      80/79%          77.4/81.7
