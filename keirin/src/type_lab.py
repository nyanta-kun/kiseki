#:
#:    ＝ **10万+ 率は両窓ともほぼ同一**（ROI は探索で 8pt 低いが確認では同値＝
#:    窓で一致しないので「同等」と読む）。看板の本数は置き場所では動かない
#:    （`P(払戻>=X) = 帯ROI × 予算/X` の恒等式・`SIGNBOARD_TYPES` の節と同じ）。
#:
#: 🟢 **型は B / C / D を採る**（落とす側での型別・探索 / 確認）:
#:
#:      型   枠/日      ROI%(探索 / 確認)        10万+%(探索 / 確認)
#:      B   1.62〜1.80  91.3 / 81.6              5.13 / 3.48
#:      C   2.18〜3.15  90.3 / 79.4              4.84 / 4.00
#:      D   2.91〜3.30  85.1 / 81.5              4.46 / 4.03
#:      F  10.19〜14.37 70.9 / 75.5              3.70 / 3.73
#:      E   3.15〜3.47  60.8 / 70.6              3.43 / 3.61
#:      A   2.19〜2.40  57.2 / 48.7              3.21 / 2.59   ← 最悪
#:
#:    **B+C+D をまとめると 枠/日 4.85〜5.77・的中 5.6%・ROI 81.0〜87.9%・
#:    払戻中央 12.0〜13.7万円・10万+ 3.95〜4.70%/商品**（＝5本/日で **月5.9〜7.1回**）。
#:    🔴 型A・型E は両窓とも ROI が壁の下なので入れない。型F は現行の
#:    `SIGNBOARD_TYPES` が決勝系で既に使っているので、ここでは重複させない。
#:    ⚠️ ROI の CI は ±20〜30pt と広い。**採用の根拠は「10万+ を増やせること」**で、
#:       ROI が上がることではない（型別の順序は点推定が両窓で一致するだけ）。
#:
#: 🔴 **これは「日ごとに何本」という配分の話なので `sell_plans_for` には入らない。**
#:    あの関数はレース単位の純関数で日次の状態を持たない。実際の割り当ては
#:    `netkeirin_submit_type_lab` の日次上限のすぐ横で行う（上限に当たった行を
#:    捨てる代わりに看板枠へ差し替える）。ここに置くのは**判定の純関数だけ**。
#: ⚠️ 7車のみ（`SIGNBOARD_N_ENTRIES` と同じ理由で9車は未測定）。
#: ⚠️ 実測と再現: `docs/highpay_5slots_2026_09_06.md`
HIGHPAY_TYPES: tuple[str, ...] = ("B", "C", "D")
#: 1日に置く本数。**既存の看板枠 `F_sign`（決勝系・約3本/日）とは別枠**で数える。
HIGHPAY_SLOTS_PER_DAY = 5
#: 高額枠を置く車数。**これ以外には置かない**（9車は未測定）。
HIGHPAY_N_ENTRIES = 7

#: 5本の内訳（`HIGHPAY_BIG_TARGET` / `HIGHPAY_BIG_SLOTS`）は
#: `SIGNBOARD_N_ENTRIES` の直後にある（`PLANS` を組む前に要るため）。
#: 高額枠として売りうるプラン。
HIGHPAY_PLAN_KEYS: frozenset[str] = (
    frozenset(f"{t}_sign" for t in HIGHPAY_TYPES)
    | frozenset(f"{t}_big" for t in HIGHPAY_TYPES))


def highpay_plan_for(type_label: str | None, n_entries: int | None,
                     n_done: int = 0) -> str | None:
    """日次上限で捨てるレースに置く**高額枠**のプラン。置けなければ None。

    `n_done` はその日に既に出した高額枠の本数（0 始まり）。**本数の上限は
    ここでは見ない**（呼び出し側の日次の状態）。ここが決めるのは
    「この型・この車数なら置いてよいか」と「何本目だから sign か big か」だけ。

    >>> [highpay_plan_for("B", 7, i) for i in range(5)]
    ['B_sign', 'B_big', 'B_sign', 'B_big', 'B_sign']
    >>> highpay_plan_for("D", 7)
    'D_sign'
    >>> highpay_plan_for("C", 7, 1)
    'C_big'
    >>> highpay_plan_for("A", 7) is None
    True
    >>> highpay_plan_for("F", 7) is None
    True
    >>> highpay_plan_for("B", 9) is None
    True
    >>> highpay_plan_for(None, 7) is None
    True
    """
    if int(n_entries or 0) != HIGHPAY_N_ENTRIES:
        return None
    if str(type_label or "") not in HIGHPAY_TYPES:
        return None
    kind = "big" if (int(n_done) + 1) in HIGHPAY_BIG_SLOTS else "sign"
    return f"{type_label}_{kind}"


SELLABLE_PLAN_KEYS: frozenset[str] = (
    frozenset(SELL_PLANS)
    | {f"{t}_sign" for t in SIGNBOARD_TYPES}
    | {TYPE_F_SELL_DEFAULT, TYPE_F_SELL_LINE}
    | set(TYPE_F_SELL_BY_RACE_TYPE.values())
    | HIGHPAY_PLAN_KEYS)


def plans_for(type_label: str, n_entries: int = 7,
              race_type: str | None = None) -> list[Plan]:
    """その型で**組む**買い方。**車数と種別で組まないものを外す**。

    7車は `PLANS` をそのまま返す（8プラン全部を `type_lab_picks` へ残す）。
    9車だけ、型F を `NINE_CAR_TYPE_F_*` の条件へ絞る。

    🔴 **これは「生成」の関数で「入稿」の関数ではない。** 実際に売るものは
       `sell_plans_for()`。7車は A_pay / F_hit を組むが売らない——比較台を
       残すためで、混同すると売っていない側の成績が消える。

    🔴 **2026-08-30 から 9車の型F も種別で落とさない。** 以前は決勝以外を空にして
       いたが、それは「生成」を止める形で「売らない」を実現していた。
       **比較台が消えるので良くない**（売らなかった側の成績が事後に測れない）。
       売る／売らないは `sell_plans_for` の責務へ寄せた。

    >>> [p.key for p in plans_for("F")]
    ['F_hit', 'F_pay', 'F_line', 'F_sign', 'F_big']
    >>> [p.key for p in plans_for("F", 9, "決勝")]
    ['F_hit', 'F_pay', 'F_line', 'F_sign', 'F_big']
    >>> [p.key for p in plans_for("F", 9, "準決勝")]
    ['F_hit', 'F_pay', 'F_line', 'F_sign', 'F_big']
    >>> [p.key for p in plans_for("A", 9, "特選")]
    ['A_hit', 'A_pay', 'A_trio', 'A_ana', 'A_sign', 'A_big']
    """
    return [p for p in PLANS.values() if p.type_label == type_label]


def sell_plans_for(type_label: str, n_entries: int = 7,
                   race_type: str | None = None, *,
                   pw_ent: float | None = None,
                   trio_ok: bool | None = None) -> list[Plan]:
    """その型で **netkeirin へ入稿する**買い方（`SELL_PLANS` で絞ったもの）。

    🔴 **必ず 0 個か 1 個**。型は排他なので、これが1レース1商品を構造的に保証する。
       2つ返るようになったら優先順位の設計が別途要る＝設計が変わった合図なので、
       `tests/test_type_lab_submit.py` が全型・全車数で 1 以下を固定している。

    >>> [p.key for p in sell_plans_for("A")]
    ['A_hit']
    >>> [p.key for p in sell_plans_for("F")]
    ['F_hit']

    🔴 **9車の型F だけ `SELL_PLANS` を使わない**（2026-08-30）。決勝は `F_pay`・
       それ以外は `F_line`（**9車だけ三連複**・2026-09-06）と分かれるので、
       固定の集合では表せない。ここでも返すのは**1つだけ**なので
       1レース1商品は保たれる。7車の決勝以外は `F_hit`（三連単12点）のまま。

    >>> [p.key for p in sell_plans_for("F", 9, "決勝")]
    ['F_pay']
    >>> [p.key for p in sell_plans_for("F", 9, "準決勝")]
    ['F_line']
    >>> [p.key for p in sell_plans_for("F", 9, None)]
    ['F_line']
    >>> [p.key for p in sell_plans_for("A", 9, "特選")]
    ['A_hit']
    >>> [p.key for p in sell_plans_for("F", 7)]
    ['F_hit']

    🔴 **型A だけ3つに分かれる**（2026-08-31・`docs/type_lab/type_a_upset_2026_08_31.md` §12）。
       型は排他なので**共食いではなく棲み分け**で、ここでも返すのは1つだけ:

         ① `pw_ent >= ANA_PW_ENT_MIN`（1着率が読めない上位10%）→ `A_ana`（穴狙い）
         ② そうでなく `trio_ok`（三連複2点が入稿ゲートを通る）→ `A_trio`
         ③ 残り → `A_hit`（現行）

       🔴 **判定できないものは A_hit へ倒す**（`pw_ent`/`trio_ok` が None なら現行のまま）。
          `passes_axis_gate` と同じ思想で、分からないことを理由に商品を変えない。
       🔴 **7車だけ**。`ANA_PW_ENT_MIN` は7車の分位で、9車に当てると絶対値切りになる。

    >>> [p.key for p in sell_plans_for("A", 7, pw_ent=1.50, trio_ok=True)]
    ['A_ana']
    >>> [p.key for p in sell_plans_for("A", 7, pw_ent=1.20, trio_ok=True)]
    ['A_trio']
    >>> [p.key for p in sell_plans_for("A", 7, pw_ent=1.20, trio_ok=False)]
    ['A_hit']
    >>> [p.key for p in sell_plans_for("A", 7)]
    ['A_hit']
    >>> [p.key for p in sell_plans_for("A", 9, pw_ent=1.50, trio_ok=True)]
    ['A_hit']
    """
    plans = plans_for(type_label, n_entries, race_type)
    # 🔴 看板枠は**他のどの分岐よりも先**に見る。型A の3分割も 9車の型F の種別分岐も
    #    「その型で何を売るか」の話なので、看板枠に指定された型ではそれらを上書きする。
    #    ここでも返すのは1つだけなので 1レース1商品は保たれる。
    if (type_label in SIGNBOARD_TYPES
            and int(n_entries or 0) == SIGNBOARD_N_ENTRIES
            and (not SIGNBOARD_RACE_TYPES
                 or str(race_type or "") in SIGNBOARD_RACE_TYPES)):
        return [p for p in plans if p.key == f"{type_label}_sign"]
    if type_label == "A":
        key = "A_hit"
        if int(n_entries or 0) == ANA_N_ENTRIES:
            if pw_ent is not None and float(pw_ent) >= ANA_PW_ENT_MIN:
                key = "A_ana"
            elif trio_ok:
                key = "A_trio"
        return [p for p in plans if p.key == key]
    # 🔴 **車数を問わない**（2026-08-31）。7車も 9車も「決勝は F_pay・それ以外は F_hit」。
    #    以前は 9車だけの規則で、7車は `SELL_PLANS` の `F_pay` に落ちていた。
    if type_label == "F":
        key = TYPE_F_SELL_BY_RACE_TYPE.get(
            str(race_type or ""), TYPE_F_SELL_DEFAULT)
        # 🔴 **9車の非決勝だけ三連複へ**（2026-09-06）。決勝系は `F_pay` のまま
        #    （9車の決勝は年40件前後しか無く、ここだけでは採否を決められない）。
        #    7車は測っていないので触らない——車数をまたいだ移植でこのリポジトリは
        #    繰り返し失敗している（7C の定数・3ヘッド軸・7M1）。
        if (key == TYPE_F_SELL_DEFAULT
                and int(n_entries or 0) == TYPE_F_LINE_N_ENTRIES):
            key = TYPE_F_SELL_LINE
        return [p for p in plans if p.key == key]
    return [p for p in plans if p.key in SELL_PLANS]


def build_legs(shape: RaceShape, plan: Plan,
               pred_odds: Mapping[tuple[int, ...] | frozenset, float],
               probs: Mapping[tuple[int, ...] | frozenset, float],
               ) -> list[tuple[int, ...]] | list[frozenset] | None:
    """買い目のリスト。組めなければ None。

    pred_odds / probs のキーは三連単なら (1着,2着,3着) のタプル、三連複なら frozenset。
    """
    order = list(shape.order)
    a1, a2 = order[0], order[1]
    rest = order[2:]

    if plan.bet_type == "trio":
        if plan.structure == "line_axis2_flow":
            # 🔴 **軸は `shape.order` の上位2車ではなくラインから取る**
            #    （`shape.line_pair` = 3着内率の合計が最大のラインの上位2車）。
            #    9車型F の実測（paper 1,958R・探索2025 / 確認2026）:
            #      軸2車がそろう率 36.48 / 37.55%（`order` の上位2車は 35.35 / 31.02%）
            #    軸1・軸2が同一ラインのレースでは**現行の軸と100%一致する**ので、
            #    いま当てられているレースは動かない。効くのは別ライン群だけ。
            #    ⚠️ 軸2を全体の3着内率上位から取ると 31.0%（確認窓）まで落ちる。
            #       **軸2はライン内から取ること。**
            pair = tuple(shape.line_pair)
            if len(pair) != 2:
                return None
            a, b = pair
            cs: list[frozenset] = []
            s = 0.0
            for c in order:
                if c in pair:
                    continue
                k = frozenset({a, b, c})
                o = pred_odds.get(k)
                if not _pos(o):
                    continue
                # 🔴 **超えたら止める（`continue` ではない）。** 相手は3着内率の
                #    降順なので、ここで飛ばして先の高オッズ点を拾うと「安い相手を
                #    外して穴だけ買う」別の商品になる。実測したのは前方から
                #    積める限り積む形。
                if plan.sigma_max and s + 1.0 / float(o) > plan.sigma_max:
                    break
                cs.append(k)
                s += 1.0 / float(o)
                if plan.max_legs and len(cs) >= plan.max_legs:
                    break
            return cs if len(cs) >= TRIO_LINE_MIN_LEGS else None
        if plan.structure == "axis2_flow":
            # 軸2車＋相手を確率降順に n_partners 点。順序を捨てるだけで
            # 相手選びは A_hit と同じ（p3 の並び順）。
            cs = [frozenset({a1, a2, c}) for c in rest[:plan.n_partners]]
            cs = [c for c in cs if _pos(pred_odds.get(c))]
            return cs if len(cs) == plan.n_partners else None
        if plan.structure != "axis2_drop_fav":
            return None
        cs = [frozenset({a1, a2, c}) for c in rest]
        cs = [c for c in cs if _pos(pred_odds.get(c))]
        if len(cs) <= plan.n_partners:
            return None
        cs.sort(key=lambda c: float(pred_odds[c]))          # 予測オッズ昇順＝人気順
        cs = cs[1:]                                          # 最人気を1点外す
        cs.sort(key=lambda c: -float(probs.get(c, 0.0)))
        out = cs[:plan.n_partners]
        return out if len(out) == plan.n_partners else None

    # ── 三連単 ──
    if plan.structure == "fixed12":
        out = [(a1, a2, c) for c in rest[:plan.n_partners]]
    elif plan.structure == "axis1_second2":
        seconds = [a2, order[2]] if len(order) > 2 else [a2]
        pool = [c for c in rest if c not in seconds][:plan.n_partners]
        out = [(a1, s, c) for s in seconds for c in pool]
    elif plan.structure == "all6":
        pool = rest[:plan.n_partners]
        out = []
        for c in pool:
            trio = (a1, a2, c)
            out.extend(p for p in itertools.permutations(trio))
    elif plan.structure == "bust_top":
        # 🔴 **軸1（p3 1位）を買い目から完全に外す。** 「軸1が3着にも入らない」
        #    ことに賭ける商品なので、軸1を含む目を1点でも買うと商品が矛盾する。
        pool = set(order[1:])
        cand = [k for k, v in pred_odds.items()
                if _pos(v) and len(set(k)) == 3 and set(k) <= pool]
        cand.sort(key=lambda k: -float(probs.get(k, 0.0)))
        out = [tuple(k) for k in cand[:plan.max_legs or 5]]
        if len(out) < 2:
            return None
    elif plan.structure == "signboard":
        # 🔴 **看板枠。** 「ダッチにしたときどの点が当たっても計画払戻 T 円以上」を
        #    制約 Σ(1/予測オッズ) <= 予算/T として表し、その枠に確率降順で詰める。
        #    ダッチ配分（`alloc="dutch"`）と対で初めて意味を持つ構成なので、
        #    配分を変えるなら商品が別物になると考えること。
        #
        # 🔴 **並べ方は確率順で固定する。** EV順・オッズ順・確率上位k点→EV順 も
        #    測ったが、10万+/日 も ROI も窓をまたいで判別できない
        #    （`SIGNBOARD_TYPES` の実測表）。**選び方は本数を動かさない。**
        # 🔴 **`plan.bust` は「軸1を含む目を全部外す」**（`bust_top` と同じ狙いを
        #    点数ではなく計画払戻で決める形）。30万超はこの形でしか出ない——
        #    計画15万は探索・確認あわせて 3,180R で **50万+ が0件**
        #    （`docs/highpay_5slots_2026_09_06.md` 9章）。
        cap = float(BUDGET) / float(plan.target or SIGNBOARD_TARGET)
        pool = set(order[1:]) if plan.bust else None
        cand = [k for k, v in pred_odds.items()
                if _pos(v) and len(set(k)) == 3
                and (pool is None or set(k) <= pool)
                and float(v) >= plan.min_odds
                and (not plan.max_odds or float(v) <= plan.max_odds)]
        cand.sort(key=lambda k: -float(probs.get(k, 0.0)))
        out, s = [], 0.0
        for k in cand:
            o = float(pred_odds[k])
            if s + 1.0 / o > cap:
                continue
            out.append(tuple(k))
            s += 1.0 / o
        if not out:
            return None
    elif plan.structure == "prob_top":
        cand = [k for k, v in pred_odds.items()
                if _pos(v) and float(v) >= plan.min_odds and len(set(k)) == 3]
        cand.sort(key=lambda k: -float(probs.get(k, 0.0)))
        out = []
        s = 0.0
        for k in cand:
            o = float(pred_odds[k])
            if plan.sigma_max and s + 1.0 / o > plan.sigma_max:
                continue
            out.append(tuple(k))
            s += 1.0 / o
            if plan.max_legs and len(out) >= plan.max_legs:
                break
        if plan.sigma_max and len(out) < 2:
            return None
        out = _insert_underband(out, plan, pred_odds)
    else:
        return None

    out = [tuple(c) for c in out if len(set(c)) == 3 and _pos(pred_odds.get(tuple(c)))]
    return out or None


def _pos(v) -> bool:
    try:
        return v is not None and float(v) > 0
    except (TypeError, ValueError):
        return False


def _insert_underband(out: list, plan: Plan, pred_odds: Mapping) -> list:
    """帯（`plan.min_odds`）で切っている目から**最も人気の1点**を買い足す。

    点数は変えない（確率最下位の1点と入れ替える）。差し込む目が無ければそのまま返す。

    🔴 **選ぶのは「モデルが最有力とみる目」ではなく「最も人気の目」**（2026-09-08）。
       対照実験で、差し込む目の選び方はほとんど効かないと分かっている
       （型C・入稿ゲート通過分・探索2025 / 確認2026・表示的中）:

         モデル確率1位   32.75 / 32.65%
         無作為 20 seed  中央 32.35 / 32.29%（範囲 31.82〜32.97）← 確率1位と区別できない
         **市場1位（最安）** **33.56 / 33.54%**

       ＝効いているのは「帯の下の目を1点でも持つこと」自体であって、モデルの
       目利きではない。文面・画面もそのつもりで書くこと（「順当だから買う」ではない）。

    🔴 **1点だけ**。2点差し込むと +3.81 / +2.93pt まで落ちる（1点は +6.47 / +5.28pt）。
       2点目を入れると平均想定払戻が2万円ゲートを割るレースが増え、
       `GATE_FALLBACK` 経由で現行へ戻る回数が増えるため（発火 74% → 34%）。
    🔴 **先頭へ入れる。** 末尾だと `line_legs`（ライン決着への差し替え）が
       後ろから m 点を置き換えるときに、差し込んだ1点が真っ先に消える。
    """
    if not plan.underband_min or not plan.min_odds or len(out) < 2:
        return out
    have = set(out)
    cand = [k for k, v in pred_odds.items()
            if _pos(v) and len(set(k)) == 3 and k not in have
            and plan.underband_min <= float(v) < plan.min_odds]
    if not cand:
        return out
    top = min(cand, key=lambda k: (float(pred_odds[k]), tuple(k)))
    return [top] + list(out)[:len(out) - 1]


# ───────────────────────────── 配分 ─────────────────────────────

def allocate(legs: Sequence, pred_odds: Mapping, probs: Mapping, plan: Plan,
             budget: int = BUDGET, unit: int = UNIT) -> dict | None:
    """買い目 -> 賭け金。組めなければ None。

    'dutch' … 賭け金 ∝ 1/予測オッズ（**払戻を全点で揃える**）
    'conf'  … 各点に floor = 予算×floor_mult ÷ 予測オッズ を置き、残りを**確率に比例**して配る
              （一番期待していない点は floor のまま＝最低 floor_mult 倍・自信のある点ほど厚い）

    🔴 **賭け金が 0 円になった点は返さない**（2026-08-28）。ダッチ配分では
       極端に高い予測オッズの点の取り分が 1 単位（100円）に満たず 0 円になる。
       `prob_top` が Σ(1/予測オッズ) の枠を超えた候補を `break` せず `continue` する
       ため、B_hit ではこれが常態化していた（**実測 3,052行＝B_hit の 61.7%**）:

         - `n_legs` が**実際に買う点数と違う**
         - `pred_min_payout`（画面の「想定最低」）の中央値が **0円**
         - `pred_mean_payout` が 0 点で薄まり、B_hit の設計「想定平均払戻 3万円の床」を
           下回る（中央 26,461円）
         - その点が当たると `hit=true, payout=0` になる（実績0件だが構造上起きうる）

       ⚠️ **お金はほとんど動かない。** 4,742倍の点の重みは 1/4,742 で、落としても
          他の点の配分はほぼ変わらない（＝商品の変更ではなく記録を実態に合わせる修正）。
       ⚠️ 買う集合そのものを変えたい（`continue` → `break`）場合は別の話で、
          そちらは商品が変わるので測ってから決めること。
    """
    legs = list(legs)
    for _ in range(len(legs)):
        stakes = _allocate_once(legs, pred_odds, probs, plan, budget, unit)
        if stakes is None:
            return None
        funded = [c for c in legs if stakes[c] > 0]
        if len(funded) == len(legs):
            return stakes
        if not funded:
            return None
        legs = funded          # 0円の点を外して配り直す
    return None


def _allocate_once(legs: Sequence, pred_odds: Mapping, probs: Mapping, plan: Plan,
                   budget: int, unit: int) -> dict | None:
    k = len(legs)
    n_units = budget // unit
    if k == 0 or k > n_units:
        return None
    o = [float(pred_odds[c]) for c in legs]
    if any(x <= 0 for x in o):
        return None

    if plan.alloc == "dutch":
        w = [1.0 / x for x in o]
        units = _proportional(w, n_units)
    else:
        floor = [max(int(math.ceil(budget * plan.floor_mult / x / unit)), 1) for x in o]
        if sum(floor) > n_units:
            return None
        rest = n_units - sum(floor)
        p = [max(float(probs.get(c, 0.0)), 0.0) for c in legs]
        add = _proportional(p, rest) if rest > 0 and sum(p) > 0 else [0] * k
        if rest > 0 and sum(p) <= 0:
            add = _proportional([1.0] * k, rest)
        units = [f + a for f, a in zip(floor, add)]
    return {c: u * unit for c, u in zip(legs, units)}


def _proportional(w: Sequence[float], n_units: int) -> list[int]:
    """重み w で n_units を配る（各要素0以上・合計ちょうど n_units）。

    配り方の骨格は `unit_distribution` に一本化した（3方針の比較表もそちらにある）。
    ここの方針: 切り捨て → 余りは「比例誤差が最大の点」へ（オッズを見ない）。
    重みが全部0のときだけ均等割りにするのはこの関数固有の扱い。
    """
    k = len(w)
    if n_units <= 0:
        return [0] * k
    if sum(w) <= 0:
        base = [n_units // k] * k
        for i in range(n_units - sum(base)):
            base[i] += 1
        return base
    units = distribute_units(
        dict(enumerate(w)), n_units,
        leftover=FLOOR_THEN_LARGEST_REMAINDER, order=list(range(k)),
    )
    return [units[i] for i in range(k)]


def mean_expected_payout(stakes: Mapping, pred_odds: Mapping) -> float:
    """入稿する買い目の想定払戻の**平均**（円）。表示と検証で同じ値を使う。"""
    if not stakes:
        return 0.0
    return sum(stakes[c] * float(pred_odds[c]) for c in stakes) / len(stakes)


