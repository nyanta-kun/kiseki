#:      λr1.9 帯無視      30.43 / 31.21%      +0.97 / +1.22      —          26.63 / 25.83%
#:
#: 🔴🔴 **帯（`plan.min_odds`）を守ること。** 守らないと効果は倍になるが、
#:    **増分は丸ごと `E_hit`（+2.96/+3.59 ↔ 帯順守 +0.12/−0.12）＝帯30倍を実質外した分**。
#:    それは DESIGN 2.4 の「価格の道具」を黙って外す操作で、4.3 の「③帯下決着」を
