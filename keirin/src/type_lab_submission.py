def _base_legs(legs: Sequence[Mapping]) -> list:
    """本線（下帯）の買い目だけ。**役割の無い行は本線**とみなす。

    >>> _base_legs([{"combo": "1-2-3"}, {"combo": "4-5-6", "role": "band"}])
    [{'combo': '1-2-3'}]
    """
    return [lg for lg in legs if (lg.get("role") or ROLE_BASE) == ROLE_BASE]


