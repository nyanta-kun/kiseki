"""3着内率（`pred_top3_pct`）の後段較正（2026-08-17 新設）。

## なぜ要るのか

モデル全体の較正は良い（2025-01〜 予測 42.40% / 実測 41.81%・ずれ +0.59pt）が、
**勝ち上がり戦と上位グレードだけ系統的に過大評価**している:

    決勝 +2.84pt / GII +2.10pt / GI +2.09pt / GIII +1.52pt / 準決勝 +1.27pt
    （時間帯・バンク周長・級班・選手クラスは 0.5〜0.65pt で完全にフラット）

しかも決勝では**上位帯に偏る**（予測30%以上の帯で +2.6〜4.9pt・20%未満はずれない）
＝「決勝は拮抗するのにモデルが平場と同じ差をつけている」。

🔴 **順位は変わらないので軸選定は狂わない**（実測 16,146レースで順位変化 0件）。
   壊れるのは **p3 の絶対値を見るゲート**（7C の 1.44 / 9C の 1.30）で、
   膨らんだ p3 で閾値を越えるため**質を伴わないレースが通る**。実測（2026年）:

    7車 決勝    通過 52.3% / 通過分の二軸 56.8% / ゲートの利き **+8.5pt**
    7車 その他  通過 53.5% / 通過分の二軸 63.8% / ゲートの利き +11.3pt

   ＝ 決勝は最も通るのに最も効いていない。

## 直し方

ロジット空間の Platt scaling `p' = σ(a·logit(p) + b)` をセグメント別に当てる。
`a<1` が「分散を縮める」＝拮抗を表現する補正。**単調変換なので順位は不変**。

⚠️ **`pred_top3_pct` を書き換えない。** 表示・他ランク・過去データへ波及する。
   ここで計算した値は**ゲート専用**として candidates に別キーで載せる
   （`race_point` を表示用の値で上書きして特徴量を汚染した事故と同じ轍を踏まない）。

## 効果（2025で当てて2026で評価・前向き）

| 区分 | ずれ 較正前→後 | ゲート通過→二軸→利き |
|---|---|---|
| 決勝 | +2.53 → **-0.49pt** | 52.3%→31.7% / 56.8%→**65.7%** / +8.5→**+17.4pt** |
| 準決勝 | +1.41 → +0.21pt | ほぼ不変 |
| 9車・上位グレード | — | 43.2%→**15.4%** / 43.1%→**54.5%** / +8.7→**+20.2pt** |

母集団は 7C -7% / 9C -6%（**閾値は据え置き＝絞る**・2026-08-17 ユーザー判断）。

## 🔴 較正そのものが不要になりつつある（2026-08-20 実測）

新モデル（66特徴・命名是正後）でバックフィルした指数で 2025年を測り直すと、
**冒頭に書いた過大評価がほぼ消えている**:

| 区分 | n | 予測p3 | 実測 | 乖離 |
|---|---|---|---|---|
| その他 | 151,033 | 42.53 | 42.77 | −0.24 |
| **決勝** | 12,199 | 43.14 | 42.92 | **+0.22**（新設時 **+2.84**） |
| 準決勝 | 27,888 | 43.02 | 43.11 | −0.09 |

**このモジュールが解こうとしていた問題は、モデル側で解消された**と見られる。
決勝は実力が拮抗し**ライン構成が勝敗を分ける**ので、ライン先頭比較の特徴が
最も効く場面であることと整合する。

⚠️ **まだ外さない。** (1) 上位グレード（GI/GII/GP）は a=0.834 と依然強い圧縮が要る、
(2) 決勝は n=1,700レース相当で係数が振れる、(3) 外すとゲート通過率が動くので
別途の検証が要る。**次に較正を引き直したときも決勝が恒等に近ければ、
決勝・準決勝のセグメントは落とす候補**。

## 係数の保守

🔴 **固定値を焼き込んだままにしないこと。** 窓を替えて推定し直すと決勝の a が
   0.877(2025) → 0.971(2026) と動く（標本が薄い。決勝は 2025 で約1,800レース）。
   `scripts/fit_p3_calibration.py` で定期的に引き直す。
🔴 **過去の再構築へそのまま当てると in-sample** になる（学習窓を含むため）。
   walk-forward で過去を作り直すときは、その時点までで推定した係数を使うこと。
"""
from __future__ import annotations

import math

# 係数の推定窓。引き直したらここも更新する（どの期間の較正かが追えなくなる）。
# 🔴 2026-08-20 に引き直した。**推定窓は同じ 2025年**だが、ライン特徴の追加(60→66)と
#    命名・定義の是正でモデルが替わったため係数が動いた。決勝×F級の a が
#    0.8740 → 0.9620（+0.088）＝**新モデルは決勝での過大評価が旧モデルより小さい**。
#    準決勝×F級は 1.0582 → 0.9969 でほぼ恒等になった。
#    ⚠️ 決勝は n=11,757行（約1,700レース）と薄く、モデル改善か標本の振れかは
#       この1回では区別できない。**旧モデル由来の係数を当て続けると決勝が
#       過剰補正になりゲート通過率が不当に下がる**ので更新側へ倒した。
FIT_WINDOW = "2025-01-01〜2025-12-31"  # 再推定 2026-08-20（モデル更新に追随）

# セグメント → (a, b)。`a<1` が分散を縮める補正。
# 交差セルは**学習1,500行以上**のものだけ持つ（決勝×上位は201行しかなく推定できない）。
_CROSS: dict[tuple[str, str], tuple[float, float]] = {
    ("決勝",   "F級"):       (0.9620, -0.0463),   # n=11,757
    ("準決勝", "F級"):       (0.9969, -0.0294),   # n=26,792
    ("その他", "F級"):       (0.9896, -0.0150),   # n=123,213
    ("その他", "GIII"):      (0.9777, -0.0864),   # n=15,368
    ("その他", "上位"):      (0.8396, -0.2088),   # n=4,136
}
_BY_GRADE: dict[str, tuple[float, float]] = {
    "F級":   (0.9891, -0.0197),   # n=161,762
    "GIII":  (0.9860, -0.0840),   # n=17,126
    "上位":  (0.8341, -0.2082),   # n=4,470
}
_BY_RACE_TYPE: dict[str, tuple[float, float]] = {
    "決勝":   (0.9670, -0.0469),   # n=12,345
    "準決勝": (0.9976, -0.0331),   # n=28,296
    "その他": (0.9868, -0.0264),   # n=142,717
}
_IDENTITY = (1.0, 0.0)


def race_type_group(race_type: str | None) -> str:
    """レース種別を較正のセグメントへ畳む。

    ⚠️ **「準決勝」を先に見る**（「決勝」に部分一致で当たるため）。
       ここを取り違えると準決勝が決勝の強い補正(a=0.874)を受けて壊れる。
    """
    rt = race_type or ""
    if "準決勝" in rt:
        return "準決勝"
    if "決勝" in rt:
        return "決勝"
    return "その他"


def grade_group(cup_grade: int | None) -> str:
    """開催グレードを較正のセグメントへ畳む（GII以上 / GIII / F級）。

    🔴 **不明（None）は「F級」へ倒す**。`cup_grade` は 2026-08-14 に保存を
       始めた列で 2024年以前は NULL。母集団の98%が F級 なので、そこへ寄せるのが
       最も無害（F級の補正はほぼ恒等 a=0.985）。上位側へ倒すと過去のレースが
       強い圧縮を受けてゲートが不当に厳しくなる。
    """
    if cup_grade is None:
        return "F級"
    g = int(cup_grade)
    if g >= 4:
        return "上位"
    if g == 3:
        return "GIII"
    return "F級"


def coefficients(race_type: str | None, cup_grade: int | None) -> tuple[float, float]:
    """セグメントの (a, b)。交差 → グレード → 種別 → 恒等 の順にフォールバックする。

    交差セルを全部は持てない（決勝×上位 201行・準決勝×上位 367行）ので、
    薄いところは1次元の係数で受ける。
    """
    rt, gr = race_type_group(race_type), grade_group(cup_grade)
    return (_CROSS.get((rt, gr))
            or _BY_GRADE.get(gr)
            or _BY_RACE_TYPE.get(rt)
            or _IDENTITY)


def calibrate_top3(p: float, race_type: str | None, cup_grade: int | None) -> float:
    """3着内率を較正する。`p` は 0-1 スケール。

    🔴 **単調変換**なので、同じレース内の順位は絶対に変わらない。
       軸選定・相手の並びは較正の前後で同一になる（テストで固定してある）。
    """
    if p is None:
        return 0.0
    p = min(max(float(p), 1e-6), 1.0 - 1e-6)
    a, b = coefficients(race_type, cup_grade)
    z = a * math.log(p / (1.0 - p)) + b
    if z >= 0:                       # オーバーフローを避ける形で sigmoid
        return 1.0 / (1.0 + math.exp(-z))
    e = math.exp(z)
    return e / (1.0 + e)


def calibrated_p3_sum_top2(top3_probs: dict[int, float],
                           race_type: str | None,
                           cup_grade: int | None) -> float | None:
    """**ゲート専用**の「上位2車の3着内率合計」。

    ⚠️ 軸そのものは較正前の値で選んでよい（順位が同じなので結果は変わらない）。
       ここが返すのは 7C/9C の閾値と比べる値だけ。
    """
    if not top3_probs or len(top3_probs) < 2:
        return None
    cal = {f: calibrate_top3(p, race_type, cup_grade) for f, p in top3_probs.items()}
    top2 = sorted(cal, key=lambda f: (-cal[f], f))[:2]
    return cal[top2[0]] + cal[top2[1]]
