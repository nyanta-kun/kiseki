"""看板レース（決勝・特選クラス）の判定（2026-08-10 新設）。

## なぜ kiseki 側に置くのか

2026-08-09 に「看板レースには必ず推奨を出す」方針になり、
自動入稿（keirin リポジトリ `scripts/submit_marquee_wt.py`）と
Web一覧の★表示の**2箇所で同じ判定**が要るようになった。

初版はフロント（`frontend/src/app/keirin/page.tsx`）に TypeScript で
キーワードを写していたが、**判定が3言語・2リポジトリに散る**のは
このプロジェクトが繰り返し事故を起こしている型なので、
kiseki 側の正本をここに置き、API が `is_marquee` を返す形へ移した。

✅ **2026-08-11 に一本化済み。このファイルが唯一の正本。**
   入稿の実行側（`keirin/src/marquee.py`）はここをファイル読み込みして
   キーワードと判定関数をそのまま束縛する（keirin が別リポジトリだった間は
   写していた）。**判定を変えるときはここだけを変える。**

⚠️ ここは**標準ライブラリ以外を import しないこと**。keirin 側は
   自分の venv（FastAPI も SQLAlchemy も入っていない）から
   `importlib` でこのファイルを直接読み込むため、依存を足すと
   入稿側が起動時に落ちる。

## 判定

    看板 = race_type に 決勝 / 特選 / 選抜 / 特秀 のいずれかを含む
           ただし「準決勝」は除く

⚠️ **レース番号（最終R＝決勝）で判定しない。** ガールズ決勝が 6R と 12R の
   両方に置かれる開催が実在する（2026-08-09 佐世保）。逆に最終Rが一般戦の
   こともある。

⚠️ **「準決勝」は「決勝」を部分一致で拾う。** 除外しないと準決勝
   （全体の約14.5%）が看板に入り、判定が意味を失う。
"""

from __future__ import annotations

MARQUEE_KEYWORDS: tuple[str, ...] = ("決勝", "特選", "選抜", "特秀")
MARQUEE_EXCLUDE: tuple[str, ...] = ("準決勝",)

# ---------------------------------------------------------------------------
# 大会（6日制の特別開催）の予選（2026-08-13 新設）
#
# GI/GII 級の開催は「一次予選 → 二次予選 → 準決勝 → 決勝」の形を取り、
# 予選であっても注目度と売上が高い。実測（2026-08-11 松山・オールスター競輪）で
# **1レースあたりの有償pt が他会場の5.0倍**だった。
#
# ところが従来の看板判定（決勝/特選/選抜）はこれらを拾わないため、
# **最も売れる開催の予選に商品が1つも出ない**状態だった
# （2026-08-13 松山 6R〜11R が丸ごと無推奨）。
#
# 🔴 **これは「看板」とは別概念**。看板は「売上が集まる決勝クラス」で、
#    こちらは「大会の予選」。同じ MARQUEE_KEYWORDS へ混ぜると Web の★の
#    意味が変わり、`rank_7t1_is_target_race_type`（決勝系レース）の母集団も
#    動かしてしまうため、**別の関数に分ける**。
#
# ⚠️ **通常の「予選」を含めてはいけない。** 接頭辞の無い「予選」は
#    282開催・2,264レースに現れる日常のレースで、含めると判定が意味を失う。
#    ここに挙げるのは**接頭辞つきの形だけ**（一予選・二次予選Ａ 等）。
#
# ⚠️ 取りこぼし: 接頭辞の無い「予選」でも9車の開催が 33レース(5開催・1.5年)ある。
#    race_type だけでは通常の予選と区別できないので拾わない（全体の約2%）。
#    車数を見れば分けられるが、判定の signature を変えると
#    共有している呼び出し側（Web の★・入稿バッチ）を全て触ることになる。
#
# ⚠️ **「特別選抜予選」は「選抜」を部分一致で拾うので既に看板**（ここには不要）。
BIG_EVENT_KEYWORDS: tuple[str, ...] = (
    "一予選", "二予選",          # 最頻（861 / 517 レース・2025-01 以降）
    "一次予選", "二次予選",      # 「二次予選Ａ」「一次予選１」等
    "東予選", "西予選",          # 東西対抗形式（「東予選(第１走)」等）
)


def is_marquee_race(race_type: str | None) -> bool:
    """race_type が看板レース（決勝・特選クラス）か。

    ⚠️ 除外を先に見る（「準決勝」が「決勝」を部分一致で拾うため）。
    ⚠️ **大会の予選は含まない**（`is_big_event_race`）。看板は売上が集まる
       決勝クラスを指す語で、意味が違う。
    """
    if not race_type:
        return False
    if any(k in race_type for k in MARQUEE_EXCLUDE):
        return False
    return any(k in race_type for k in MARQUEE_KEYWORDS)


def is_big_event_race(race_type: str | None) -> bool:
    """race_type が**大会（6日制の特別開催）の予選**か。

    GI/GII 級の開催でしか出ない形式。看板ではないが注目度と売上が高いので、
    **入稿の穴埋め対象としては看板と同じに扱う**（`is_fill_target`）。
    """
    if not race_type:
        return False
    return any(k in race_type for k in BIG_EVENT_KEYWORDS)


# 🔴 このグレード以上の開催は **全レース**を穴埋め対象にする（2026-08-14・ユーザー判断
#    「グレードの競輪場はキーワードより優先」）。GIII(3) 以上＝ GIII/GII/GI/GP。
#
# なぜ race_type のキーワードでは足りないか:
#   2026-08-14 松山（オールスター競輪・GI・11R）で、キーワードが拾えたのは
#   「選抜(1)」の 3〜5R とその前後だけで **7R〜11R（準々Ａ/Ｂ・シャイニングスター賞）
#   が丸ごと無推奨**だった。大会の番組名は開催ごとに自由度が高く、
#   キーワードを足し続けても追いつかない。開催のグレードは番組名と違って
#   構造化された値なので、そちらを先に見る。
#
# ⚠️ **キーワード判定は消さない**。`cup_grade` は 2026-08-14 に保存を始めた列で、
#    それ以前のレースと取得に失敗した開催では NULL になる。NULL のときは
#    従来どおりキーワードで判定する（fail-open ではなく従来動作へのフォールバック）。
#
# ⚠️ この定数は `keirin_cup_grade.BIG_EVENT_MIN_GRADE` と同じ値でなければならないが、
#    **import してはいけない**（このファイルは keirin 側が自分の venv から
#    直接読み込むため、標準ライブラリ以外に依存できない）。
#    一致は `tests/test_keirin_marquee.py` が突き合わせている。
FILL_ALL_MIN_GRADE = 3


def is_fill_target(race_type: str | None, cup_grade: int | None = None) -> bool:
    """入稿の穴埋め対象か。

    判定の順序（**グレードが先**）:
      1. 開催グレードが `FILL_ALL_MIN_GRADE` 以上 → **無条件で対象**（全レース）
      2. それ以外 → 看板 **または** 大会の予選（race_type のキーワード）

    🔴 穴埋めの判定はここを使う。`is_marquee_race` を直接見ると
       大会の予選が漏れる（2026-08-13 に実際に漏れた）。
    """
    if cup_grade is not None and int(cup_grade) >= FILL_ALL_MIN_GRADE:
        return True
    return is_marquee_race(race_type) or is_big_event_race(race_type)
