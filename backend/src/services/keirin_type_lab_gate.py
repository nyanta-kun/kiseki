def axis_priority(plan_key: str, axis_sum: float | None) -> float:
    """上限に当たったときの**残す順**（0〜1・大きいほど先に残す）。

    そのプランの探索窓の分布の中で `axis_sum` がどこに位置するかを返す。

    🔴 **判定できないものは 0.5（中庸）**。`passes_axis_gate` の「通す」と同じ思想で、
       分からないことを理由に先頭にも末尾にも置かない。閾値表を持たないプランが
       増えても、その商品だけが必ず消える／必ず残るという偏りを作らない。

    >>> axis_priority("A_hit", 1.90)      # 上端
    1.0
    >>> axis_priority("A_hit", 1.0)       # 下端より下
    0.0
    >>> axis_priority("知らないプラン", 1.5)
    0.5
    >>> axis_priority("A_hit", None)
    0.5
    """
    qs = AXIS_PRIORITY_QUANTILES.get(plan_key)
    if not qs or axis_sum is None:
        return 0.5
    try:
        v = float(axis_sum)
    except (TypeError, ValueError):
        return 0.5
    n = len(qs) - 1                       # 区間の数（分位が 11 個なら 10 区間）
    for i in range(n + 1):
        if v < qs[i]:
            return i / n
    return 1.0
