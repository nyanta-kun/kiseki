"""型ラボの「軸信頼ゲート」— 判定の唯一の正本（2026-08-27 新設）。

## これは何か

各プランの中で **軸信頼（= 上位2車の3着内率の合計）が下位のレースを外す**フィルタ。
`keirin.type_lab_picks.axis_sum` と比べるだけなので、**買い目を作り直す必要がない**
（実地検証の最中でも既存の行に後から当てられる）。

## 根拠（`keirin/docs/type_lab/ev_axis_rank_2026_08_27.md`）

探索窓 2026-01〜04 でプランごとに五分位を作り、確認窓 2026-05〜08-26 で評価:

| | 件/日 | 表示的中 | ROI | 全体との差 |
|---|---|---|---|---|
| 絞らない | 51.1 | 24.48% | 80.1% | — |
| 下位2/5 を外す | **29.5** | **27.79%** | **85.0%** | **+4.9pt CI[+0.1, +9.9]** |

**無作為に同数を落とす対照 20 seed に 20/20 で勝つ**（対照の中央 80.2%）。
レース属性（種別・型・場）で絞った案はいずれも対照に負けていた
（`race_filter_2026_08_27.md`）ので、対照を超えたのはこれが初めて。

🔴 **絶対閾値では効かない。** 本番 7C の `RANK_7C_P3_SUM_MIN = 1.44` を含め
1.20〜1.50 のどこで切っても差は 0 を跨ぐ。絶対値で切ると D/E/F がまるごと消えて
プラン構成が変わり、否定済みの「型で絞る」と同じ操作になる。
**効くのは "各プランの中で相対的に下を外す" 形だけ**なので、閾値はプランごとに持つ。

🔴 **まだ採用ではない。** 確認窓を判断に使ってしまっており（一度きりを消費）、
CI 下限 +0.1pt はぎりぎりで、向きが両窓一致するのは 6プラン中 3プラン。
**前向きの実地で確かめるための表示用フィルタ**として置いている。

🔴 **標準ライブラリ以外を import しないこと。** keirin 側がこのファイルを直接
読み込んで束縛する余地を残す（`keirin_marquee.py` / `keirin_p3_calibration.py` と同じ制約）。
"""
from __future__ import annotations

#: プランごとの軸信頼の下限。**探索窓（2026-01-01〜04-30）のプラン内 40 パーセンタイル**
#: ＝「下位2/5 を外す」境界。`A_pay` は `A_hit` と、`F_pay` は `F_hit` と同じレースに
#: 出るので同じ値になる（実測で一致を確認済み）。
#: ⚠️ プランの買い方を変えたら **この表も測り直すこと**（母集団が変われば分位も動く）。
AXIS_GATE_MIN: dict[str, float] = {
    "A_hit": 1.601,
    "A_pay": 1.601,
    "B_hit": 1.539,
    "C_hit": 1.511,
    "D_hit": 1.341,
    "E_hit": 1.323,
    "F_hit": 1.310,
    "F_pay": 1.310,
}

#: 上の表を作った探索窓。数字の出どころを行に残しておく。
AXIS_GATE_SOURCE_WINDOW = ("2026-01-01", "2026-04-30")
#: 下位何割を外す設計か（表示・ドキュメント用）。
AXIS_GATE_DROP_RATIO = 0.4


def passes_axis_gate(plan_key: str, axis_sum: float | None) -> bool:
    """そのプランの軸信頼ゲートを通るか。

    🔴 **判定できないものは通す**（`True` を返す）。閾値を持たないプランや
       `axis_sum` が無い行を落とすと、ゲートを入れた瞬間に**理由の分からない
       件数減**が起きる。落とすなら「測って下だった」ときだけにする。

    >>> passes_axis_gate("A_hit", 1.70)
    True
    >>> passes_axis_gate("A_hit", 1.50)
    False
    >>> passes_axis_gate("A_hit", None)
    True
    >>> passes_axis_gate("知らないプラン", 0.1)
    True
    """
    if axis_sum is None:
        return True
    floor = AXIS_GATE_MIN.get(plan_key)
    if floor is None:
        return True
    return float(axis_sum) >= floor
